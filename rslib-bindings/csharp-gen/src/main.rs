//! Generates the typed C# client of Ankit.Native, the C# counterpart of the
//! `_backend_generated.py` file Anki generates for its Python client.
//!
//! Every backend method becomes a method of the `RslibBackend` partial class
//! that forwards to `RslibBackend.Call` with the right service and method
//! indices. Request and response types are the classes Grpc.Tools generates
//! from the same `.proto` files.
//!
//! Usage: `cargo run -p csharp-gen -- <output.cs>`, after rslib has been
//! built, so that the descriptor set at `DESCRIPTORS_BIN` exists.

use std::env;
use std::fmt::Write;
use std::fs;

use anki_proto_gen::get_services;
use anki_proto_gen::BackendService;
use anki_proto_gen::Method;
use anyhow::Context;
use anyhow::Result;
use prost_reflect::DescriptorPool;
use prost_reflect::MessageDescriptor;

/// Same services Anki leaves out of its Python client
const SKIPPED_SERVICES: &[&str] = &["BackendAnkidroidService", "BackendFrontendService"];

const EMPTY_MESSAGE: &str = "anki.generic.Empty";

fn main() -> Result<()> {
    let output = env::args()
        .nth(1)
        .context("usage: csharp-gen <output.cs>")?;
    let descriptors = env::var("DESCRIPTORS_BIN").context("DESCRIPTORS_BIN is not set")?;
    let descriptors = fs::read(&descriptors)
        .with_context(|| format!("cannot read {descriptors}, build rslib first"))?;
    let pool = DescriptorPool::decode(descriptors.as_ref())?;
    let (_, services) = get_services(&pool);

    let mut out = String::new();
    write_header(&mut out);
    for service in &services {
        if SKIPPED_SERVICES.contains(&service.name.as_str()) {
            continue;
        }
        writeln!(out, "    // {}", service.name)?;
        writeln!(out)?;
        for method in service.all_methods() {
            write_method(&mut out, service, method)?;
        }
    }
    out.push_str("}\n");

    // Only touch the file when it changes, to keep MSBuild incremental builds intact
    if fs::read_to_string(&output).ok().as_deref() != Some(out.as_str()) {
        fs::write(&output, out).with_context(|| format!("cannot write {output}"))?;
    }
    Ok(())
}

fn write_header(out: &mut String) {
    out.push_str(
        "// <auto-generated>
// Generated by rslib-bindings/csharp-gen from Anki's descriptor set, do not edit.
// </auto-generated>

#nullable enable

namespace Ankit.Native;

public sealed partial class RslibBackend
{
",
    );
}

/// Writes, for example:
///
/// ```cs
/// public global::Anki.Generic.Bool CreateBackup(global::Anki.Collection.CreateBackupRequest request) =>
///     Call(3, 2, request, global::Anki.Generic.Bool.Parser);
/// ```
fn write_method(out: &mut String, service: &BackendService, method: &Method) -> Result<()> {
    let name = method.proto.name();
    let input = method.proto.input();
    let output = method.proto.output();
    let (service_idx, method_idx) = (service.index, method.index);

    if let Some(comments) = &method.comments {
        writeln!(out, "    /// <summary>")?;
        for line in comments.lines() {
            writeln!(out, "    /// {}", xml_escape(line.trim()))?;
        }
        writeln!(out, "    /// </summary>")?;
    }

    let (params, request) = if input.full_name() == EMPTY_MESSAGE {
        (String::new(), "null")
    } else {
        (format!("{} request", csharp_type(&input)), "request")
    };

    if output.full_name() == EMPTY_MESSAGE {
        writeln!(out, "    public void {name}({params}) =>")?;
        writeln!(out, "        Call({service_idx}, {method_idx}, {request});")?;
    } else {
        let output = csharp_type(&output);
        writeln!(out, "    public {output} {name}({params}) =>")?;
        writeln!(
            out,
            "        Call({service_idx}, {method_idx}, {request}, {output}.Parser);"
        )?;
    }
    writeln!(out)?;
    Ok(())
}

/// The class name protoc's C# generator gives a message, e.g.
/// `anki.import_export.CsvMetadata.Delimiter` becomes
/// `global::Anki.ImportExport.CsvMetadata.Types.Delimiter`.
fn csharp_type(message: &MessageDescriptor) -> String {
    let mut names = vec![message.name().to_string()];
    let mut parent = message.parent_message();
    while let Some(p) = parent {
        names.push("Types".into());
        names.push(p.name().to_string());
        parent = p.parent_message();
    }
    names.reverse();

    let namespace = message
        .package_name()
        .split('.')
        .map(pascal_case)
        .collect::<Vec<_>>()
        .join(".");
    format!("global::{namespace}.{}", names.join("."))
}

/// Mirrors protoc's `UnderscoresToPascalCase`
fn pascal_case(segment: &str) -> String {
    let mut out = String::new();
    let mut capitalize = true;
    for c in segment.chars() {
        if c == '_' {
            capitalize = true;
        } else if c.is_ascii_digit() {
            out.push(c);
            capitalize = true;
        } else if capitalize {
            out.push(c.to_ascii_uppercase());
            capitalize = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn xml_escape(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}
